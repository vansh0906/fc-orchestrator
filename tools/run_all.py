#!/usr/bin/env python3
"""Build, unit-test, and run every study; writes results/*.json, results/RESULTS.md and docs/img/results.png.

    python3 tools/run_all.py      # about 1 minute
"""
import json
import os
import shutil
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import chaos  # noqa: E402
import loadtest  # noqa: E402

RES = os.path.join(ROOT, "results")
ENV = {**os.environ, "JAVA_TOOL_OPTIONS": ""}


def main():
    os.makedirs(RES, exist_ok=True)
    print("build + unit tests", flush=True)
    subprocess.run([os.path.join(HERE, "build.sh")], check=True, env=ENV)

    print("floor model: batch-window sweep and golden-section search", flush=True)
    sim = json.loads(subprocess.run(["java", "-cp", os.path.join(ROOT, "out"), "fc.Sim"], check=True, env=ENV,
                                    capture_output=True, text=True).stdout)
    save("planning.json", sim)

    print("chaos test (kill -9 both services under load)", flush=True)
    work = tempfile.mkdtemp(prefix="fc-chaos-")
    ch = chaos.run(work)
    shutil.rmtree(work, ignore_errors=True)
    save("chaos.json", ch)

    print("load test (fsync per write vs group commit)", flush=True)
    lt = [loadtest.run_mode(m) for m in ("PER_WRITE", "GROUP_COMMIT")]
    save("loadtest.json", lt)

    plot(sim, ch, lt)
    report(sim, ch, lt)
    ok = ch["lost"] == 0 and ch["completed_twice"] == 0 and ch["tasks_twice"] == 0
    print(f"done: lost {ch['lost']}, completed twice {ch['completed_twice']} -> results/RESULTS.md")
    return 0 if ok else 1


def save(name, obj):
    with open(os.path.join(RES, name), "w") as f:
        json.dump(obj, f, indent=2)


def best(sim, planner):
    rows = [r for r in sim["sweep"] if r["planner"] == planner]
    return min(rows, key=lambda r: r["p95_s"])


def plot(sim, ch, lt):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    fig, ax = plt.subplots(1, 3, figsize=(16, 4.4))
    for planner, st in (("greedy", "o-"), ("lp", "s-")):
        rows = [r for r in sim["sweep"] if r["planner"] == planner]
        ax[0].plot([r["window_s"] for r in rows], [r["p95_s"] for r in rows], st,
                   label={"greedy": "greedy (nearest station)", "lp": "LP (simplex)"}[planner])
    g = sim["golden_section"]["lp"]
    ax[0].plot([t[0] for t in g["trace"]], [t[1] for t in g["trace"]], "x", color="k", label="golden-section evaluations (LP)")
    ax[0].set_xscale("log")
    ax[0].set(xlabel="batch window (s)", ylabel="p95 order latency (s, simulated)", title="Planning: assignment and batching")
    ax[0].legend(fontsize=8)

    s = [r for r in ch["series"] if r["open"] is not None]
    ax[1].plot([r["t"] for r in s], [r["open"] for r in s], "-", label="open orders")
    for e in ch["events"]:
        ax[1].axvline(e["t"], color="r" if "kill" in e["event"] else "g", ls="--", lw=0.8)
        ax[1].text(e["t"], ax[1].get_ylim()[1] * 0.92, e["event"].replace("order-service", "orders"), rotation=90,
                   fontsize=7, va="top", ha="right")
    ax[1].axhline(chaos.ALARM_BACKLOG, color="gray", ls=":", lw=0.8)
    ax[1].set(xlabel="seconds", ylabel="open orders", title=f"Chaos: kill -9 both services ({ch['orders']} orders, 0 lost)")
    ax[1].legend(fontsize=8)

    x = range(len(lt))
    ax[2].bar([i - 0.2 for i in x], [r["orders_per_s"] for r in lt], 0.4, label="accepted orders/s")
    ax2 = ax[2].twinx()
    ax2.bar([i + 0.2 for i in x], [r["p99_ms"] for r in lt], 0.4, color="tab:orange", label="p99 latency (ms)")
    ax[2].set_xticks(list(x), [r["mode"].replace("_", " ").lower() for r in lt])
    ax[2].set(ylabel="accepted orders/s", title="Durable accepts: fsync per write vs group commit")
    ax2.set_ylabel("p99 latency (ms)")
    ax[2].set_ylim(0, max(r["orders_per_s"] for r in lt) * 1.35)
    ax2.set_ylim(0, max(r["p99_ms"] for r in lt) * 1.35)
    ax[2].legend(loc="upper left", fontsize=8)
    ax2.legend(loc="upper right", fontsize=8)
    fig.tight_layout()
    os.makedirs(os.path.join(ROOT, "docs", "img"), exist_ok=True)
    fig.savefig(os.path.join(ROOT, "docs", "img", "results.png"), dpi=130)


def report(sim, ch, lt):
    bl, bg = best(sim, "lp"), best(sim, "greedy")
    gl, gg = sim["golden_section"]["lp"], sim["golden_section"]["greedy"]
    a = ch["analytics"]
    L = ["# Results", "", "Generated by `python3 tools/run_all.py`. The chaos and load tests run both services and the "
         "clients on one small machine; their absolute numbers vary between runs.", "",
         "## Planning (floor model, simulated time)", "",
         f"Config: {json.dumps(sim['config'])}", "",
         "| Planner | Best window (grid) | p95 latency | Travel per order | Drive-unit utilisation | Golden-section window | Golden-section p95 | Evaluations |",
         "|---|---|---|---|---|---|---|---|"]
    for name, b, g in (("greedy", bg, gg), ("LP", bl, gl)):
        L.append(f"| {name} | {b['window_s']} s | {b['p95_s']} s | {b['travel_m_per_order']} m | {b['robot_util']} | "
                 f"{g['window_s']} s | {g['p95_s']} s | {g['evaluations']} |")
    L += ["", "| Window (s) | Greedy p95 (s) | LP p95 (s) | Greedy travel (m) | LP travel (m) |", "|---|---|---|---|---|"]
    rows = {}
    for r in sim["sweep"]:
        rows.setdefault(r["window_s"], {})[r["planner"]] = r
    for w, r in sorted(rows.items()):
        L.append(f"| {w:g} | {r['greedy']['p95_s']} | {r['lp']['p95_s']} | {r['greedy']['travel_m_per_order']} | "
                 f"{r['lp']['travel_m_per_order']} |")
    L += ["", "## Chaos test", "",
          f"{ch['orders']} orders offered at {ch['offered_rate']:g}/s for {ch['load_s']} s; all done {ch['drained_s']} s after start.", "",
          "| Check | Result |", "|---|---|",
          f"| Orders DONE | {ch['status_counts'].get('DONE', 0)} / {ch['orders']} |",
          f"| Lost | {ch['lost']} |",
          f"| Completed twice (order WAL) | {ch['completed_twice']} |",
          f"| Received twice by the allocator | {ch['tasks_twice']} |",
          f"| Client retries during the faults | {ch['client_retries']} |",
          f"| Duplicate requests absorbed (same order id) | {ch['duplicate_requests_absorbed']} |",
          f"| Duplicate completion callbacks absorbed | {ch['duplicate_callbacks_absorbed']} |", "",
          "| Event | t (s) |", "|---|---|"]
    L += [f"| {e['event']} | {e['t']} |" for e in ch["events"]]
    L += ["", "| Alarm | Fired (s) | Cleared (s) |", "|---|---|---|"]
    L += [f"| {x['alarm']} | {x['fired_s']} | {x['cleared_s']} |" for x in ch["alarms"]]
    L += ["", "End-to-end latency by when the order was accepted (SQL over the WALs):", "",
          "| Phase | Orders | p50 (ms) | p99 (ms) |", "|---|---|---|---|"]
    L += [f"| {p['phase']} | {p['orders']} | {p['p50_ms']} | {p['p99_ms']} |" for p in a["phases"]]
    L += ["", "## Load test", "", "| WAL mode | Clients | Accepted orders/s | p50 (ms) | p99 (ms) | fsyncs per order |",
          "|---|---|---|---|---|---|"]
    L += [f"| {r['mode']} | {r['clients']} | {r['orders_per_s']} | {r['p50_ms']} | {r['p99_ms']} | {r['fsyncs_per_order']} |"
          for r in lt]
    with open(os.path.join(RES, "RESULTS.md"), "w") as f:
        f.write("\n".join(L) + "\n")


if __name__ == "__main__":
    sys.exit(main())
